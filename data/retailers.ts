export function retailerSearchUrl(retailerName: string, query: string) {
  return nigeriaRetailers
    .find((retailer) => retailer.name === retailerName)
    ?.searchUrl(query);
}

export function retailerSlug(retailerName: string) {
  return retailerShoppingSlug(retailerName);
}

export function retailerBySlug(slug: string) {
  return nigeriaRetailers.find(
    (retailer) => retailerSlug(retailer.name) === slug,
  );
}

export function retailerEvidenceFor(
  retailerName: string,
): RetailerEvidence | undefined {
  const retailer = nigeriaRetailers.find((item) => item.name === retailerName);
  if (!retailer) return undefined;
  return {
    reviewStatus: retailer.reviewStatus,
    contentUse: retailer.contentUse,
    identity: retailer.identityEvidence,
    regulatorMatch: retailer.regulatorMatchEvidence,
  };
}
